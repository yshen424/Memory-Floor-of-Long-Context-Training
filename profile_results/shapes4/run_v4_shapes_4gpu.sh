# R1 BRACKETS (capacity, ±1 rung): static largest fit x=49 (fails 50); stock offload largest fit x=64 (fails 65); ladder span 1.306
#
# K-P1 SLOPES: every (shape, mechanism) line's slope within 0.01 MiB/x of the
#      table. Byte statements: no tolerance beyond measurement.
#      Named consequences: G1, G2 slope = tier-A's 84.320312 (HF expands K/V
#      to all query heads before saving, so KV-head count moves only the
#      intercept); I1/I2 slope = tier-A -6.0 / +12.0 (exactly SIX feed-forward
#      planes); V1 slope = tier-A (chunked loss: vocabulary is
#      intercept-only); D1 static slope 228.320312 -> span at perfect relief
