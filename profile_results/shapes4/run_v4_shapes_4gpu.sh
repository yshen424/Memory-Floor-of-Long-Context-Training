# K-P2 INTERCEPTS within 1 MiB of the table. The library workspace may move
#      with larger matrix multiplies; a uniform shift across a block's two
#      mechanisms is recorded as a workspace change, not a model miss.
# K-P3 R1 BRACKETS within ±1 rung: static [49, 50), stock offload [64, 65)
#      (ladder span 1.306): for a wide, shallow model the non-migratable term
#      (128.4 MiB/x) dwarfs the boundaries (64 MiB/x), so offloading buys
#      only ~1.3x the sequence length on this card.
# K-P4 FAILURES: every failing rung an OOM in step-1 backward on exactly
#      2*I/1024*x MiB (16x MiB for R1).
# KNOWN RISKS, stated before the run: (a) at vocabulary 128k the loss-
#      backward peak class (the x=8 effect) may reach higher x;
#      V1 and R1 therefore start at x=24, and a point sitting ABOVE its line
#      with its peak outside the layer replay is that class, not a slope miss.
#      (b) The feed-forward multiply's backward is predicted to stay the peak
#      operation for every shape; a miss concentrated at I1 (I/h = 2) would
#      mean attention's backward has taken over.
# Static peaks are read from step 1+ (AdamW present); x=8-class points are
# excluded by design.

export MASTER_ADDR=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n 1)
export MASTER_PORT=29900
export WORLD_SIZE=$SLURM_NTASKS
export RANK=$SLURM_PROCID
export TF_CPP_MIN_LOG_LEVEL=3
export CUDA_DEVICE_ORDER=PCI_BUS_ID
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

ATTEMPT=${SLURM_RESTART_COUNT:-0}
if [ "$ATTEMPT" = "0" ]; then ASUF=""; else ASUF="r${ATTEMPT}"; fi
echo "NODES: $SLURM_JOB_NODELIST  WORLD_SIZE: $SLURM_NTASKS  ATTEMPT: $ATTEMPT"
if [ "$SLURM_NTASKS" != "4" ]; then
    echo "WORLD SIZE IS ${SLURM_NTASKS}, NOT 4. Every prediction here is world 4."
    exit 2
fi

OUTROOT=profile_results/shapes4
mkdir -p logs "$OUTROOT"

MIN_AVAIL_GIB=100
AVAIL=$(srun --ntasks-per-node=1 bash -c \
    'echo "$(hostname) $(awk "/MemAvailable/{printf \"%d\", \$2/1048576}" /proc/meminfo)"' \
    < /dev/null)
echo "MemAvailable per node (GiB):"; echo "$AVAIL" | sed 's/^/    /'
if echo "$AVAIL" | awk -v m=$MIN_AVAIL_GIB 'NF<2 || $2<m {bad=1} END {exit !bad}'; then
    echo "PREFLIGHT FAILED: a node has under ${MIN_AVAIL_GIB} GiB MemAvailable, or did not answer."
    exit 3
fi

# block:L:hidden:intermediate:n_q:n_kv:vocab:mode:x   (generated by harness/)
ARMS="S0:32:768:2048:12:4:32000:static:24 S0:32:768:2048:12:4:32000:offload:24 W1:32:1024:2816:16:4:32000:static:16 W1:32:1024:2816:16:4:32000:offload:16 W1:32:1024:2816:16:4:32000:static:24 W1:32:1024:2816:16:4:32000:offload:24 W1:32:1024:2816:16:4:32000:static:32 W1:32:1024:2816:16:4:32000:offload:32 W2:32:1536:4096:24:8:32000:static:16 W2:32:1536:4096:24:8:32000:offload:16 W2:32:1536:4096:24:8:32000:static:24 W2:32:1536:4096:24:8:32000:offload:24 W2:32:1536:4096:24:8:32000:static:32 W2:32:1536:4096:24:8:32000:offload:32 W3:32:2048:5632:32:8:32000:static:16 W3:32:2048:5632:32:8:32000:offload:16 W3:32:2048:5632:32:8:32000:static:24 W3:32:2048:5632:32:8:32000:offload:24 W3:32:2048:5632:32:8:32000:static:32 W3:32:2048:5632:32:8:32000:offload:32 G1:32:768:2048:12:12:32000:static:16 G1:32:768:2048:12:12:32000:offload:16 G1:32:768:2048:12:12:32000:static:24 G1:32:768:2048:12:12:32000:offload:24 G1:32:768:2048:12:12:32000:static:32 G1:32:768:2048:12:12:32000:offload:32 G2:32:768:2048:12:1:32000:static:16 G2:32:768:2048:12:1:32000:offload:16 G2:32:768:2048:12:1:32000:static:24 G2:32:768:2048:12:1:32000:offload:24 G2:32:768:2048:12:1:32000:static:32 G2:32:768:2048:12:1:32000:offload:32 I1:32:768:1536:12:4:32000:static:16 I1:32:768:1536:12:4:32000:offload:16 I1:32:768:1536:12:4:32000:static:24 I1:32:768:1536:12:4:32000:offload:24 I1:32:768:1536:12:4:32000:static:32 I1:32:768:1536:12:4:32000:offload:32 I2:32:768:3072:12:4:32000:static:16 I2:32:768:3072:12:4:32000:offload:16 I2:32:768:3072:12:4:32000:static:24 I2:32:768:3072:12:4:32000:offload:24 I2:32:768:3072:12:4:32000:static:32 I2:32:768:3072:12:4:32000:offload:32 V1:32:768:2048:12:4:128000:static:24 V1:32:768:2048:12:4:128000:offload:24 V1:32:768:2048:12:4:128000:static:32 V1:32:768:2048:12:4:128000:offload:32 V1:32:768:2048:12:4:128000:static:40 V1:32:768:2048:12:4:128000:offload:40 D1:128:768:2048:12:4:32000:static:16 D1:128:768:2048:12:4:32000:offload:16 D1:128:768:2048:12:4:32000:static:24 D1:128:768:2048:12:4:32000:offload:24 D1:128:768:2048:12:4:32000:static:32 D1:128:768:2048:12:4:32000:offload:32 D1:128:768:2048:12:4:32000:static:40 D1:128:768:2048:12:4:32000:offload:40 R1:16:2048:8192:32:8:128256:static:24 R1:16:2048:8192:32:8:128256:offload:24 R1:16:2048:8192:32:8:128256:static:32 R1:16:2048:8192:32:8:128256:offload:32 R1:16:2048:8192:32:8:128256:static:40 R1:16:2048:8192:32:8:128256:offload:40 RS:16:2048:8192:32:8:128256:static:47 RS:16:2048:8192:32:8:128256:static:48 RS:16:2048:8192:32:8:128256:static:49 RS:16:2048:8192:32:8:128256:static:50 RS:16:2048:8192:32:8:128256:static:51 RS:16:2048:8192:32:8:128256:static:52 RO:16:2048:8192:32:8:128256:offload:62 RO:16:2048:8192:32:8:128256:offload:63 RO:16:2048:8192:32:8:128256:offload:64 RO:16:2048:8192:32:8:128256:offload:65 RO:16:2048:8192:32:8:128256:offload:66 RO:16:2048:8192:32:8:128256:offload:67"

CHUNK=256; DT=fp16; ATTN=sdpa_mem_efficient; NORM=input; SEED=1234; NSTEPS=2; BS=1
PORT_BASE=${MASTER_PORT}
IDX=0
NARM=$(echo $ARMS | wc -w)
CLOSED=""

for ARM in $ARMS; do
    OLDIFS=$IFS; IFS=:; set -- $ARM; IFS=$OLDIFS
    BLOCK=$1; NL=$2; HID=$3; INTER=$4; NH=$5; NKV=$6; VOC=$7; MODE=$8; X=$9; SQ=$((X * 1024))
    case " $CLOSED " in *" $BLOCK "*) echo "SKIP ${BLOCK} x=${X}: ladder closed below"; continue ;; esac
    case "$MODE" in
        static)  MODE_FLAGS="--layer_checkpoint" ;;
        offload) MODE_FLAGS="--layer_checkpoint --activation_offload" ;;
    esac
    TAG=${BLOCK}_L${NL}_h${HID}_i${INTER}_q${NH}_kv${NKV}_v${VOC}_${MODE}_x${X}_n${NSTEPS}_c${CHUNK}
    OUTDIR=${OUTROOT}/${SLURM_JOB_ID}${ASUF}-${TAG}_b${BS}_${DT}_mem_efficient_world4
    mkdir -p "$OUTDIR"
    IDX=$((IDX + 1))
    echo "ARM ${IDX}/${NARM} [${BLOCK}] L=${NL} h=${HID} I=${INTER} heads ${NH}/${NKV} v=${VOC} ${MODE} x=${X} -> ${OUTDIR}"
    srun torchrun \
        --nnodes=$SLURM_NNODES --nproc_per_node=1 \
        --rdzv_id=${SLURM_JOB_ID}${ASUF}_a${IDX} --rdzv_backend=c10d \
        --rdzv_endpoint=$MASTER_ADDR:$((PORT_BASE + IDX)) \
        train_fsdp_profile.py \
            --hidden_size ${HID} --intermediate_size ${INTER} --num_layers ${NL} \
            --num_heads ${NH} --num_kv_heads ${NKV} --vocab_size ${VOC} \
            --dtype ${DT} --attn_impl ${ATTN} \
            --seq_len ${SQ} --batch_size ${BS} --steps ${NSTEPS} \
            --chunked_ce ${CHUNK} ${MODE_FLAGS} \
            --fused_rmsnorm ${NORM} --use_cache off --seed ${SEED} \
            --disable_hbm_drift --output_dir "$OUTDIR" \
            < /dev/null 2> >(tee "$OUTDIR/stderr.txt" >&2) \
        || echo "ARM ${IDX} (${BLOCK}, ${MODE}, x=${X}) DID NOT COMPLETE. Read its stderr.txt: (0) node failure / socket timeout -> re-run, closes nothing; (1) in a SLOPE block (S0..R1) every x is predicted to fit with margin, so ANY OOM there is a model miss or the loss-backward class -> record the request and the peak instant; (2) in RS/RO an OOM in step-1 backward on exactly 16x MiB is the DESIGNED closure; (3) a host pinned-memory failure is a host limit, not capacity."
    if [ ! -f "$OUTDIR/steps_rank0.json" ]; then
        case "$BLOCK" in RS|RO) echo "LADDER ${BLOCK} CLOSED at x=${X}."; CLOSED="$CLOSED $BLOCK" ;; esac
    fi
    sleep 20
done

echo "RUN COMPLETE: ran ${IDX} of ${NARM} arms."
echo "READ IT WITH:  python3 tools/shape_sweep.py ${OUTROOT} --job ${SLURM_JOB_ID}${ASUF}"
echo "AFTER THE JOB: append rows to profile_results/runs_4gpu.csv (back it up first) and"
echo "move this script to ${OUTROOT}/."
