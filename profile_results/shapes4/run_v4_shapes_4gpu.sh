# ── JOB: THE SHAPE SWEEP. WORLD 4, V100 ─────────────────────────────────────
# The harness (harness/) was derived and checked at ONE shape family
# (h=768, I=2048, 12/4 heads, v=32000). This job tests it OFF that shape:
# every line below is the harness's output for the arm's configuration,
# with no new fitting.
#
# Slope blocks (static AND stock offload at every point, 2 steps):
#   S0 control (tier-A L=32)        W1-W3 width 1024/1536/2048
#   G1 MHA 12/12, G2 MQA 12/1       I1-I2 feed-forward 1536 / 3072
#   V1 vocabulary 128000            D1 depth 128 (span 6.29 -> MEASURED)
#   R1 Llama-3.2-1B-shaped: h=2048 I=8192 32/8 heads L=16 v=128256,
#      UNTIED head (the harness models embedding and head separately)
# Bracket blocks (climbing, stop at first failure, 2 steps per rung):
#   RS R1 static x=47..52           RO R1 stock offload x=62..67
#
# All: lever 3 c=256, regime B fp16/sdpa_mem_efficient, fused-input,
# cache off, b=1, seed 1234, head_dim 64 everywhere.
# Wall clock ~2.5-3 h (76 arms).

# ── THE PREDICTIONS. PRE-REGISTERED 2026-10-10, GENERATED BY harness/ ──────
# Platform constants (calibrated, not derived): workspace 31.2588 MiB;
# capacity C0 15627.64 MiB, alpha 0.163 (refit before registration).
# Lines (MiB, x = tokens/1024; steps 1+, the step-1 peak):
#   S0  L=32  h=768  I=2048 heads 12/4  v=32000   static  900.6560 + 84.320312x   offload 1098.7044 + 37.820312x   span@perfect 2.3216
