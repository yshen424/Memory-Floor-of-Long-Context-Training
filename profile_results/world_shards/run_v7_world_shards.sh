#!/bin/bash
#SBATCH --job-name=fsdp_v7_world
#SBATCH --nodes=4
#SBATCH --ntasks-per-node=1        # 1 process per node (1 GPU per node)
#SBATCH --gres=gpu:1
#SBATCH --time=03:00:00
#SBATCH --output=logs/v7world_%j.log
#SBATCH --error=logs/v7world_%j.err

# ── JOB: THE GRADIENT-SHARD COUNT ACROSS WORLD SIZE. V100, WORLDS 2/3/4 ─────
# At the floor, step 1's peak exceeds step 0's by AdamW (8 B·P/W) PLUS k fp32
# gradient shards (4 B·p_layer/W each), with k = 3 at world 4. The original
# derivation assumed k = 5 at world 4 and missed by 12.00 MiB — the one
# pre-registered intercept miss. Every existing world-4 row agrees with
# k = 3 (stock offload: 24 rows = 3.0; engine floors 7743/7744 likewise).
# HYPOTHESIS H-W1, registered here: k = W − 1. Its first test is at worlds
# it was not read from: world 2 (k = 1) and world 3 (k = 2). Same job,
# world 4 is the control (k = 3, known).
#
# Arms (3 steps each; steps 1 and 2 must agree):
#   world 2: stock offload x=80, 100; static x=48, 64
#   world 3: stock offload x=80, 100; static x=48, 64
#   world 4: stock offload x=100;     static x=48   (control)
# Static is the second control: its peak is the first replay, where no
# gradient shard is live, so its step-1 minus step-0 must be AdamW alone.
# Offload x >= 80 because below x ≈ 67 at world 2 the optimizer step
# (20 B·P/W) masks the step-0 floor.
#
# Tier-A L=64 (h 768, I 2048, 12/4 heads, v 32000), lever 3 c=256,
# regime B fp16/sdpa_mem_efficient, fused-input, cache off, b=1, seed
# 1234. Worlds 2 and 3 run on the first 2 / 3 nodes of the allocation.
# Wall clock ~1.6 h (11 arms).

# ── THE PREDICTIONS. PRE-REGISTERED 2026-10-11, GENERATED BY harness/ ──────
# (harness hash as tools/shape_sweep.py prints it: see the reader's first line;
#  step-0 floors are the harness's step-1 floor minus AdamW minus (W−1) shards.)
#   W=2: shard 12.0029 MiB, AdamW 1723.8779 MiB; static 2769.7051+132.320312x, floor 3525.8897+37.820312x
#     offload x=80:  step1+ 6551.515; step0 4815.634  (k=3 -> 4791.628, k=5 -> 4767.622); step1-step0 = 1735.881
#     offload x=100: step1+ 7307.921; step0 5572.040  (k=3 -> 5548.034, k=5 -> 5524.028); step1-step0 = 1735.881
#     static  x=48:  step1+ 9121.080; step0 7397.202; step1-step0 = 1723.878
#     static  x=64:  step1+ 11238.205; step0 9514.327; step1-step0 = 1723.878
#   W=3: shard 8.0020 MiB, AdamW 1149.2520 MiB; static 1907.7662+132.320312x, floor 2419.8912+37.820312x
#     offload x=80:  step1+ 5445.516; step0 4280.260  (k=3 -> 4272.258, k=5 -> 4256.254); step1-step0 = 1165.256
#     offload x=100: step1+ 6201.922; step0 5036.667  (k=3 -> 5028.665, k=5 -> 5012.661); step1-step0 = 1165.256
#     static  x=48:  step1+ 8259.141; step0 7109.889; step1-step0 = 1149.252
#     static  x=64:  step1+ 10376.266; step0 9227.014; step1-step0 = 1149.252
#   W=4 (control): shard 6.0015, AdamW 861.9390
#     offload x=100: step1+ 5648.923; step0 4768.980; step1-step0 = 879.943  (7747/7756/7758: 879.944)
#     static  x=48:  step1+ 7828.172; step0 6966.233; step1-step0 = 861.939
#
# W-P1 (the decider): offload step1 − step0 = AdamW + (W−1) shards to ±0.05 MiB
#      at worlds 2 and 3, i.e. k = 1.000 and 2.000 (read k = (diff − AdamW)/shard).
#      Falsified by any other whole k; a non-integer k means the increment is
#      not made of shards at all.
# W-P2 (out-of-sample intercepts at new worlds): every step-1+ peak on its
#      harness line to ±0.05 MiB. The sharded state moves as 12 B·P/W; the
#      gradient pile at the floor (61 shards) is predicted world-independent in
#      COUNT at step 1+.
# W-P3 (control): static step1 − step0 = AdamW exactly at every world; world-4
#      offload repeats 879.944.
# W-P4: steps 1 and 2 identical to 0.01 MiB on every arm (steady state).
# What a W-P1 pass buys: the one miss becomes "missed once, then predicted
#      at two new worlds". A pass does NOT name the storage;
#      the world-2 offload x=80 snapshots (--cuda_snapshot, an observer)
#      (step 2) and the one-step world-2 offload x=80 snapshot (step 0) are
#      there to name it: tools/peak_census.py on both, then the size-census
#      difference is the k blocks (and AdamW's state).

export MASTER_ADDR=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n 1)
export MASTER_PORT=29900
export TF_CPP_MIN_LOG_LEVEL=3
export CUDA_DEVICE_ORDER=PCI_BUS_ID
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

ATTEMPT=${SLURM_RESTART_COUNT:-0}
if [ "$ATTEMPT" = "0" ]; then ASUF=""; else ASUF="r${ATTEMPT}"; fi
echo "NODES: $SLURM_JOB_NODELIST  NNODES: $SLURM_NNODES  ATTEMPT: $ATTEMPT"
if [ "$SLURM_NNODES" != "4" ]; then
    echo "ALLOCATION IS ${SLURM_NNODES} NODES, NOT 4. This job needs 4 (worlds 2, 3 and 4)."
    exit 2
fi
ALLNODES=($(scontrol show hostnames "$SLURM_JOB_NODELIST"))

OUTROOT=profile_results/world_shards
mkdir -p logs "$OUTROOT"

MIN_AVAIL_GIB=100
AVAIL=$(srun --ntasks-per-node=1 bash -c \
    'echo "$(hostname) $(awk "/MemAvailable/{printf \"%d\", \$2/1048576}" /proc/meminfo)"' \
    < /dev/null)
echo "MemAvailable per node (GiB):"; echo "$AVAIL" | sed 's/^/    /'
if echo "$AVAIL" | awk -v m=$MIN_AVAIL_GIB 'NF<2 || $2<m {bad=1} END {exit !bad}'; then
    echo "PREFLIGHT FAILED: a node has under ${MIN_AVAIL_GIB} GiB MemAvailable, or did not answer."
    exit 3
fi

# Run from a private copy of the driver taken at job start, on the shared
# filesystem (/tmp is node-local).
CODE=${OUTROOT}/code_${SLURM_JOB_ID}${ASUF}
mkdir -p "$CODE"
cp -r train_fsdp_profile.py fsdp_profiler.py chunked_ce.py fused_rmsnorm.py memory_manager "$CODE"/
echo "code snapshot: $CODE ($(sha1sum train_fsdp_profile.py | cut -c1-12))"

# world:mode:x[:snap|snap0]  (snap0: a ONE-step run, so its snapshot is step 0)
ARMS="2:offload:80:snap 2:offload:80:snap0 2:offload:100 2:static:48 2:static:64 3:offload:80 3:offload:100 3:static:48 3:static:64 4:offload:100 4:static:48"

NL=64; HID=768; INTER=2048; NH=12; NKV=4; VOC=32000
CHUNK=256; DT=fp16; ATTN=sdpa_mem_efficient; NORM=input; SEED=1234; NSTEPS=3; BS=1
IDX=0
NARM=$(echo $ARMS | wc -w)

for ARM in $ARMS; do
    OLDIFS=$IFS; IFS=:; set -- $ARM; IFS=$OLDIFS
    WS=$1; MODE=$2; X=$3; SNAP=${4:-}; SQ=$((X * 1024))
    case "$MODE" in
        static)  MODE_FLAGS="--layer_checkpoint" ;;
        offload) MODE_FLAGS="--layer_checkpoint --activation_offload" ;;
    esac
    SNAP_FLAGS=""; NS=$NSTEPS
    case "$SNAP" in snap) SNAP_FLAGS="--cuda_snapshot" ;; snap0) SNAP_FLAGS="--cuda_snapshot"; NS=1 ;; esac
    # the first WS nodes of the allocation; the rendezvous host (node 0) is always among them
    NODES=$(IFS=,; echo "${ALLNODES[*]:0:$WS}")
    TAG=V7_L${NL}_h${HID}_${MODE}_x${X}_n${NS}_c${CHUNK}
    OUTDIR=${OUTROOT}/${SLURM_JOB_ID}${ASUF}-${TAG}_b${BS}_${DT}_mem_efficient_world${WS}
    mkdir -p "$OUTDIR"
    IDX=$((IDX + 1))
    echo "ARM ${IDX}/${NARM} world ${WS} (${NODES}) ${MODE} x=${X} ${SNAP} -> ${OUTDIR}"
    srun --nodes=${WS} --ntasks=${WS} --ntasks-per-node=1 --nodelist=${NODES} torchrun \
        --nnodes=${WS} --nproc_per_node=1 \
        --rdzv_id=${SLURM_JOB_ID}${ASUF}_a${IDX} --rdzv_backend=c10d \
        --rdzv_endpoint=$MASTER_ADDR:$((MASTER_PORT + IDX)) \
        "$CODE"/train_fsdp_profile.py \
            --hidden_size ${HID} --intermediate_size ${INTER} --num_layers ${NL} \
            --num_heads ${NH} --num_kv_heads ${NKV} --vocab_size ${VOC} \
            --dtype ${DT} --attn_impl ${ATTN} \
            --seq_len ${SQ} --batch_size ${BS} --steps ${NS} \
            --chunked_ce ${CHUNK} ${MODE_FLAGS} ${SNAP_FLAGS} \
            --fused_rmsnorm ${NORM} --use_cache off --seed ${SEED} \
            --disable_hbm_drift --output_dir "$OUTDIR" \
            < /dev/null 2> >(tee "$OUTDIR/stderr.txt" >&2) \
        || echo "ARM ${IDX} (world ${WS}, ${MODE}, x=${X}) DID NOT COMPLETE. Every arm is predicted to fit with >= 4 GiB margin: (0) node failure / socket timeout / rendezvous -> re-run, closes nothing; (1) an OOM is a model miss -> record the request and the step; (2) a host pinned-memory failure is a host limit, not capacity."
    sleep 20
done

echo "RUN COMPLETE: ran ${IDX} of ${NARM} arms."
echo "READ IT WITH:  PYTHONPATH=. python3 tools/world_shards.py ${OUTROOT} --job ${SLURM_JOB_ID}${ASUF}"
echo "SNAPSHOT:      python3 tools/peak_census.py <world-2 offload x=80 OUTDIR>/cuda_snapshot_rank0.pkl"
echo "AFTER THE JOB: append rows to profile_results/runs_4gpu.csv (world 2/3/4 rows; back it up"
echo "first) and move this script to ${OUTROOT}/."
