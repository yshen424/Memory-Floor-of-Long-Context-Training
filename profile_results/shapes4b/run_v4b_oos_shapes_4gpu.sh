#
# O-P1 POINTS: every completing arm within ±0.05 MiB of its predicted peak.
#      This is the whole test of the three post-hoc terms. A miss common to
#      both mechanisms of a block is the shape term; a miss on the static
#      points of one class only is that instant.
# O-P2 INSTANTS: the decisive points, where the runner-up instant is far
#      off: O1 static x8/x24 (2nd beats 1st by 6.4/7.5 MiB), x32 (1st beats
#      2nd by 12.5), x4 (opt beats 2nd by 64); D2 offload x8-16 FLAT at
#      5489.76-5489.82 (its line would read 4990-5401); D2 static x8 (2nd
#      beats opt by only 4.3 MiB, the tightest call in the job); W2 static
#      x40/48 (1st beats 2nd by 24/48).
# O-P3 BRACKETS (capacity, ±1 rung, out of sample for the capacity model):
#      QS [112, 113), QO [168, 169); ladder span 1.500.
# O-P4 FAILURES: every failing rung an OOM in step-1 backward on exactly
#      2*I/1024*x MiB = 9.5x MiB (QS 113 -> 1073.50, QO 169 -> 1605.50).
# O-P5 NAMING (no number predicted): the O1 x=32 snapshot decides between
#      (a) a second gathered fp16 layer: one block of 2·p_layer = 33.7549 MiB
#      (17,697,280 params × 2 B) plus one 2·h·I = 8.75 MiB buffer; and
#      (b) shape-sized kernel workspace: at tier-A, 3×4 + 1.125×2 + 0.375×2 MiB
#      "workspace" blocks that should now scale with the matmul
#      sizes. The D2 x=12 snapshot names the optimizer's fourth fp32 4 B/param.
# KNOWN RISKS: (a) the vocabulary-151936 loss path at x=16 (Q1): the loss-
#      backward instant has never bound at c=256, but this is the largest
#      vocabulary run; a Q1 static x16 point ABOVE prediction with its peak in
#      the loss is that class, not a shape-term miss. (b) The QO 169 rung is
#      within 3 MiB of capacity: a fit there is a +1-rung result, inside O-P3.

export MASTER_ADDR=$(scontrol show hostnames "$SLURM_JOB_NODELIST" | head -n 1)
export MASTER_PORT=29900
export WORLD_SIZE=$SLURM_NTASKS
export RANK=$SLURM_PROCID
export TF_CPP_MIN_LOG_LEVEL=3
export CUDA_DEVICE_ORDER=PCI_BUS_ID
export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True

ATTEMPT=${SLURM_RESTART_COUNT:-0}
if [ "$ATTEMPT" = "0" ]; then ASUF=""; else ASUF="r${ATTEMPT}"; fi
echo "NODES: $SLURM_JOB_NODELIST  WORLD_SIZE: $SLURM_NTASKS  ATTEMPT: $ATTEMPT"
if [ "$SLURM_NTASKS" != "4" ]; then
    echo "WORLD SIZE IS ${SLURM_NTASKS}, NOT 4. Every prediction here is world 4."
    exit 2
fi

OUTROOT=profile_results/shapes4b
mkdir -p logs "$OUTROOT"

MIN_AVAIL_GIB=100
AVAIL=$(srun --ntasks-per-node=1 bash -c \
    'echo "$(hostname) $(awk "/MemAvailable/{printf \"%d\", \$2/1048576}" /proc/meminfo)"' \
    < /dev/null)
echo "MemAvailable per node (GiB):"; echo "$AVAIL" | sed 's/^/    /'
if echo "$AVAIL" | awk -v m=$MIN_AVAIL_GIB 'NF<2 || $2<m {bad=1} END {exit !bad}'; then
    echo "PREFLIGHT FAILED: a node has under ${MIN_AVAIL_GIB} GiB MemAvailable, or did not answer."
    exit 3
fi

# The driver must not change under a running job:
# run from a private copy of the code taken at job start, on the SHARED filesystem
# (every node must see it; /tmp is node-local). Python resolves the driver's own
# imports from the script's directory first, so the copy is self-contained.
CODE=${OUTROOT}/code_${SLURM_JOB_ID}${ASUF}
mkdir -p "$CODE"
cp -r train_fsdp_profile.py fsdp_profiler.py chunked_ce.py fused_rmsnorm.py memory_manager "$CODE"/
echo "code snapshot: $CODE ($(sha1sum train_fsdp_profile.py | cut -c1-12))"

# block:L:hidden:intermediate:n_q:n_kv:vocab:mode:x[:snap]   (generated by harness/)
ARMS="O1:24:1280:3584:20:4:50304:static:4 O1:24:1280:3584:20:4:50304:static:8 O1:24:1280:3584:20:4:50304:static:16:snap O1:24:1280:3584:20:4:50304:static:24 O1:24:1280:3584:20:4:50304:static:32:snap O1:24:1280:3584:20:4:50304:static:40 O1:24:1280:3584:20:4:50304:offload:4 O1:24:1280:3584:20:4:50304:offload:16 O1:24:1280:3584:20:4:50304:offload:24 O1:24:1280:3584:20:4:50304:offload:32 O1:24:1280:3584:20:4:50304:offload:40 Q1:24:896:4864:14:2:151936:static:16 Q1:24:896:4864:14:2:151936:static:24 Q1:24:896:4864:14:2:151936:static:40 Q1:24:896:4864:14:2:151936:static:48 Q1:24:896:4864:14:2:151936:offload:16 Q1:24:896:4864:14:2:151936:offload:24 Q1:24:896:4864:14:2:151936:offload:40 D2:96:1024:2816:16:4:32000:static:4 D2:96:1024:2816:16:4:32000:static:8 D2:96:1024:2816:16:4:32000:static:16 D2:96:1024:2816:16:4:32000:static:24 D2:96:1024:2816:16:4:32000:static:32 D2:96:1024:2816:16:4:32000:offload:8 D2:96:1024:2816:16:4:32000:offload:12:snap D2:96:1024:2816:16:4:32000:offload:16 D2:96:1024:2816:16:4:32000:offload:24 D2:96:1024:2816:16:4:32000:offload:32 W2:32:1536:4096:24:8:32000:static:4 W2:32:1536:4096:24:8:32000:static:40 W2:32:1536:4096:24:8:32000:static:48 W2:32:1536:4096:24:8:32000:offload:16 QS:24:896:4864:14:2:151936:static:109 QS:24:896:4864:14:2:151936:static:110 QS:24:896:4864:14:2:151936:static:111 QS:24:896:4864:14:2:151936:static:112 QS:24:896:4864:14:2:151936:static:113 QS:24:896:4864:14:2:151936:static:114 QS:24:896:4864:14:2:151936:static:115 QS:24:896:4864:14:2:151936:static:116 QO:24:896:4864:14:2:151936:offload:165 QO:24:896:4864:14:2:151936:offload:166 QO:24:896:4864:14:2:151936:offload:167 QO:24:896:4864:14:2:151936:offload:168 QO:24:896:4864:14:2:151936:offload:169 QO:24:896:4864:14:2:151936:offload:170 QO:24:896:4864:14:2:151936:offload:171 QO:24:896:4864:14:2:151936:offload:172"

CHUNK=256; DT=fp16; ATTN=sdpa_mem_efficient; NORM=input; SEED=1234; NSTEPS=2; BS=1
PORT_BASE=${MASTER_PORT}
IDX=0
NARM=$(echo $ARMS | wc -w)
CLOSED=""

for ARM in $ARMS; do
    OLDIFS=$IFS; IFS=:; set -- $ARM; IFS=$OLDIFS
    BLOCK=$1; NL=$2; HID=$3; INTER=$4; NH=$5; NKV=$6; VOC=$7; MODE=$8; X=$9; SNAP=${10:-}; SQ=$((X * 1024))
    case " $CLOSED " in *" $BLOCK "*) echo "SKIP ${BLOCK} x=${X}: ladder closed below"; continue ;; esac
    case "$MODE" in
        static)  MODE_FLAGS="--layer_checkpoint" ;;
        offload) MODE_FLAGS="--layer_checkpoint --activation_offload" ;;
    esac
    SNAP_FLAGS=""; [ "$SNAP" = "snap" ] && SNAP_FLAGS="--cuda_snapshot"
    TAG=${BLOCK}_L${NL}_h${HID}_i${INTER}_q${NH}_kv${NKV}_v${VOC}_${MODE}_x${X}_n${NSTEPS}_c${CHUNK}
    OUTDIR=${OUTROOT}/${SLURM_JOB_ID}${ASUF}-${TAG}_b${BS}_${DT}_mem_efficient_world4
    mkdir -p "$OUTDIR"
    IDX=$((IDX + 1))
    echo "ARM ${IDX}/${NARM} [${BLOCK}] L=${NL} h=${HID} I=${INTER} heads ${NH}/${NKV} v=${VOC} ${MODE} x=${X} ${SNAP} -> ${OUTDIR}"
    srun torchrun \
        --nnodes=$SLURM_NNODES --nproc_per_node=1 \
        --rdzv_id=${SLURM_JOB_ID}${ASUF}_a${IDX} --rdzv_backend=c10d \
        --rdzv_endpoint=$MASTER_ADDR:$((PORT_BASE + IDX)) \
        "$CODE"/train_fsdp_profile.py \
            --hidden_size ${HID} --intermediate_size ${INTER} --num_layers ${NL} \
            --num_heads ${NH} --num_kv_heads ${NKV} --vocab_size ${VOC} \
            --dtype ${DT} --attn_impl ${ATTN} \
            --seq_len ${SQ} --batch_size ${BS} --steps ${NSTEPS} \
            --chunked_ce ${CHUNK} ${MODE_FLAGS} ${SNAP_FLAGS} \
            --fused_rmsnorm ${NORM} --use_cache off --seed ${SEED} \
            --disable_hbm_drift --output_dir "$OUTDIR" \
            < /dev/null 2> >(tee "$OUTDIR/stderr.txt" >&2) \
        || echo "ARM ${IDX} (${BLOCK}, ${MODE}, x=${X}) DID NOT COMPLETE. Read its stderr.txt: (0) node failure / socket timeout -> re-run, closes nothing; (1) in a POINT block (O1..W2) every x is predicted to fit with margin, so ANY OOM there is a model miss -> record the request and the peak instant; (2) in QS/QO an OOM in step-1 backward on exactly 9.5x MiB is the DESIGNED closure; (3) a host pinned-memory failure is a host limit, not capacity."
    if [ ! -f "$OUTDIR/steps_rank0.json" ]; then
        case "$BLOCK" in QS|QO) echo "LADDER ${BLOCK} CLOSED at x=${X}."; CLOSED="$CLOSED $BLOCK" ;; esac
    fi
    sleep 20
done

echo "RUN COMPLETE: ran ${IDX} of ${NARM} arms."
echo "READ IT WITH:  PYTHONPATH=. python3 tools/shape_sweep.py ${OUTROOT} --job ${SLURM_JOB_ID}${ASUF}"
echo "SNAPSHOTS:     python3 tools/peak_liveset.py <OUTDIR>/<snapshot rank0 .pkl> <tokens per rank>"
echo "AFTER THE JOB: append rows to profile_results/runs_4gpu.csv (back it up first) and"
echo "move this script to ${OUTROOT}/."
