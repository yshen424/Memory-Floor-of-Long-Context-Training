# ── JOB: OUT-OF-SAMPLE SHAPES. WORLD 4, V100 ────────────────────────────────
# The shape sweep (7761) added three terms to harness/ POST HOC: a shape term
# (2 B·p_layer + 2 B·h·I) and two more peak instants (the second backward
# replay; the optimizer step). This job tests them on shapes NONE of them
# was fitted to, with every point placed so that only ONE instant can
# produce its predicted value. No refit.
#
# Point blocks (2 steps each):
#   O1 h=1280 I=3584 20/4 L=24 v=50304   static crosses 2nd->1st at 27.0
#   Q1 Qwen2-0.5B-shaped: h=896 I=4864 14/2 L=24 v=151936 (no qkv bias,
#      untied head)                      static crosses at 32.5
#   D2 h=1024 I=2816 16/4 L=96 v=32000   offload sits on the OPTIMIZER
#      instant at x=8-16 (flat), then on its line from x=24
#   W2 the shape-sweep shape again: the arm 7761 lost (offload x=16), and
#      static points in the FIRST-replay class, not covered at W2 before
# Bracket blocks (climbing, stop at first failure, 2 steps per rung):
#   QS Q1 static x=109..116              QO Q1 stock offload x=165..172
# Naming arms (--cuda_snapshot, an observer that leaves peaks bit-identical):
# O1 static x=32 (names the shape term's storage), O1 static x=16 (the
# second-replay instant), D2 offload x=12 (the optimizer step's unnamed
# 4 B/param).
#
# All: lever 3 c=256, regime B fp16/sdpa_mem_efficient, fused-input,
# cache off, b=1, seed 1234, head_dim 64 everywhere.
# Wall clock ~3-3.5 h (48 arms; the two ladders are ~1.5 h of it).

# ── THE PREDICTIONS. PRE-REGISTERED 2026-10-10, GENERATED BY harness/ ──────
# harness/*.py hash 35cea3147c39f44f5260a4a13e47b4d6531ea0bc, as tools/shape_sweep.py prints it;
# if the reader prints another, harness/ changed after registration.
# Platform constants (calibrated, not derived): workspace 16.2559 MiB;
# capacity C0 15627.64 MiB, alpha 0.163.
# Peak = max over the instants (MiB, x = tokens/1024, steps 1+); the instant
# each point is predicted to sit on is in parentheses.
#   O1  L=24 h=1280 I=3584 heads 20/4 v=50304  (shape term 42.5049 MiB)
#       static  1st 2044.5726+122.351562x | 2nd 2112.0823+119.851562x | opt 2655.6175+0.007812x
#               x4:2655.649(opt) x8:3070.895(2nd) x16:4029.707(2nd) x24:4988.520(2nd) x32:5959.823(1st) x40:6938.635(1st)
#       offload 1st 2466.5086+64.851562x | opt 2655.6175+0.007812x
#               x4:2725.915(1st) x16:3504.134(1st) x24:4022.946(1st) x32:4541.759(1st) x40:5060.571(1st)
#   Q1  L=24 h=896 I=4864 heads 14/2 v=151936  (shape term 36.7534 MiB)
#       static  1st 2663.2651+113.328125x | 2nd 2720.1469+111.578125x | opt 3020.9965+0.007812x
#               x16:4505.397(2nd) x24:5398.022(2nd) x40:7196.390(1st) x48:8103.015(1st)
#       offload 1st 3018.7765+73.078125x | opt 3020.9965+0.007812x
#               x16:4188.027(1st) x24:4772.652(1st) x40:5941.902(1st)
#   D2  L=96 h=1024 I=2816 heads 16/4 v=32000  (shape term 27.0039 MiB)
#       static  1st 3536.3311+241.335938x | 2nd 3579.3389+239.335938x | opt 5489.6983+0.007812x
#               x4:5489.730(opt) x8:5494.026(2nd) x16:7408.714(2nd) x24:9328.394(1st) x32:11259.081(1st)
#       offload 1st 4579.2705+51.335938x | opt 5489.6983+0.007812x
#               x8:5489.761(opt) x12:5489.792(opt) x16:5489.823(opt) x24:5811.333(1st) x32:6222.021(1st)
#   W2  L=32 h=1536 I=4096 heads 24/8 v=32000  (shape term 60.0059 MiB)
#       static  x4:4325.513(opt) x40:9725.744(1st) x48:11072.681(1st)
#       offload x16:4989.028(1st)
#   QS  Q1 static:  largest fit 112, smallest fail 113 (margin at 112 +98.2, at 113 -16.7 MiB)
